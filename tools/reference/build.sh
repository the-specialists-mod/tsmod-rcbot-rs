#!/bin/sh
# Builds the reference harness from an RCBot checkout (upstream commit b9c86c2 was used for the
# recorded files) and records the reference data the Rust tests compare against:
#
#   tools/reference/build.sh /path/to/rcbotold
#
# Nothing here runs in normal tests; the recorded files under crates/rcbot/tests/reference/ do.
set -eu
SRC=${1:?usage: build.sh <rcbotold checkout>}
D=$SRC/dlls
HERE=$(cd "$(dirname "$0")" && pwd)
OUT=$HERE/../../crates/rcbot/tests/reference
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

ex() { awk -v NAME="$2" -f "$HERE/extract.awk" "$1"; }
{
    echo '// Generated by tools/reference/build.sh from upstream RCBot sources: do not edit.'
    # AStarNode's declaration (bot_const.h) and the PATH / failed-path classes (bot.h).
    awk '/^class AStarNode/{f=1} f{print} f&&/^};/{exit}' "$D/bot_const.h"
    awk '/^typedef struct path \{/{f=1} f{print} f&&/^} PATH;/{exit}' "$D/bot.h"
    awk '/^class CBotFailedPath$/{f=1} f{print} f&&/^};/{n++; if(n==2) exit}' "$D/bot.h"
    # The waypoint flags.
    grep '^#define W_FL_' "$D/waypoint.h"
} > "$WORK/upstream_decls.h"
{
    echo '// Generated by tools/reference/build.sh from upstream RCBot sources: do not edit.'
    for f in WaypointAddPath WaypointDeletePath WaypointFindPath WaypointFlags WaypointOrigin; do ex "$D/waypoint.cpp" "$f"; done
    # AStarNode's methods and the A* itself.
    awk '/^AStarNode::AStarNode\(\)/{f=1} /^void BotTurnAtWall/{exit} f{print}' "$D/bot_navigate.cpp"
    ex "$D/bot_navigate.cpp" BotNavigate_FindPathFromTo
} > "$WORK/upstream_defs.inc"

CXX=${CXX:-g++}
CC=${CC:-gcc}
$CC -O1 -c -I"$D" "$D/miniz.c" -o "$WORK/miniz.o"
for f in miniz_tdef miniz_tinfl miniz_zip; do $CC -O1 -c -I"$D" "$D/$f.c" -o "$WORK/$f.o"; done
$CXX -std=c++17 -O1 -c -I"$D" "$D/rc_compress.cpp" -o "$WORK/rc_compress.o"
$CXX -std=c++17 -O1 -I"$WORK" -I"$D" "$HERE/harness.cpp" "$WORK"/*.o -o "$WORK/harness"

mkdir -p "$OUT"
for map in ts_dojo ts_lobby mecklenburg_b5 tm_avana crossfire ahl_museum; do
    "$WORK/harness" astar "$HERE/../../data/rcbot/waypoints/ts/$map.rcw" > "$OUT/astar_$map.txt"
done
"$WORK/harness" rcz 154 "$OUT/vis154.rcz"
"$WORK/harness" rcz 791 "$OUT/vis791.rcz"
echo "recorded into $OUT"
